"""Bake the ONEWWW screen fonts from the DejaVu TrueType files.

Output: ps_sources/frontend/onewww_font_data.c. Each glyph is a 2-bit
coverage bitmap (0 = paper, 1 and 2 = part, 3 = ink), rows padded to a byte,
first pixel in the two high bits.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "third_party/dejavu"
OUT = ROOT / "ps_sources/frontend/onewww_font_data.c"

# id, file, pixel size. The ids match onewww_font.h.
FACES = [
    ("BODY", "DejaVuSans.ttf", 12),
    ("BODY_B", "DejaVuSans-Bold.ttf", 12),
    ("BODY_I", "DejaVuSans-Oblique.ttf", 12),
    ("BODY_BI", "DejaVuSans-BoldOblique.ttf", 12),
    ("H1", "DejaVuSans-Bold.ttf", 22),
    ("H2", "DejaVuSans-Bold.ttf", 16),
    ("MONO", "DejaVuSansMono.ttf", 11),
    ("SMALL", "DejaVuSans.ttf", 10),
]
# Latin with its extensions and common signs, for all faces.
CODES = (list(range(32, 127)) + list(range(160, 384)) +
         [0x0192, 0x02C6, 0x02DC, 0x2013, 0x2014, 0x2018, 0x2019, 0x201A,
          0x201C, 0x201D, 0x201E, 0x2020, 0x2021, 0x2022, 0x2026, 0x2030,
          0x2032, 0x2033, 0x2039, 0x203A, 0x20AC, 0x2122, 0x2190, 0x2191,
          0x2192, 0x2193, 0x2212, 0x2260, 0x2264, 0x2265, 0x25A0, 0x25B6,
          0x25BA, 0x25CF, 0xFFFD])
# Greek and Cyrillic, for the regular and the bold body face only. The
# renderer takes a character that a face does not have from the body face.
MORE = list(range(0x386, 0x3CF)) + list(range(0x400, 0x460))
MORE_FACES = ("BODY", "BODY_B")


def bake(face_file, size, codes):
    font = ImageFont.truetype(str(FONTS / face_file), size)
    ascent, descent = font.getmetrics()
    glyphs = []
    bits = bytearray()
    for code in sorted(codes):
        ch = chr(code)
        advance = int(round(font.getlength(ch)))
        box = font.getbbox(ch)  # relative to the ascender line
        if box is None or box[2] <= box[0] or box[3] <= box[1]:
            glyphs.append((code, len(bits), 0, 0, 0, 0, advance))
            continue
        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
        px = img.load()
        offset = len(bits)
        for y in range(h):
            row = 0
            n = 0
            for x in range(w):
                v = px[x, y]
                level = 0 if v < 43 else 1 if v < 128 else 2 if v < 213 else 3
                row = (row << 2) | level
                n += 1
                if n == 4:
                    bits.append(row)
                    row = 0
                    n = 0
            if n:
                bits.append(row << (2 * (4 - n)))
        glyphs.append((code, offset, w, h, x0, y0, advance))
    return ascent, descent, glyphs, bits


def main():
    out = ['/* Generated by scripts/onewww_bake_font.py from DejaVu 2.37.',
           ' * Do not edit. Font licence: third_party/dejavu/LICENSE. */',
           '#include "onewww_font.h"', '']
    table = []
    total = 0
    for name, face_file, size in FACES:
        ascent, descent, glyphs, bits = bake(
            face_file, size, CODES + (MORE if name in MORE_FACES else []))
        total += len(bits) + 12 * len(glyphs)
        low = name.lower()
        out.append(f'static const uint8_t {low}_bits[] = {{')
        for i in range(0, len(bits), 16):
            out.append('    ' + ','.join(str(b) for b in bits[i:i + 16]) + ',')
        out.append('};')
        out.append(f'static const onewww_glyph_t {low}_glyphs[] = {{')
        for code, offset, w, h, x0, y0, advance in glyphs:
            out.append(f'    {{{code},{offset},{w},{h},{x0},{y0},{advance}}},')
        out.append('};')
        table.append(f'    {{{low}_glyphs, {low}_bits, {len(glyphs)}, '
                     f'{ascent}, {descent}}},  /* ONEWWW_FONT_{name} */')
    out.append('const onewww_font_t onewww_fonts[ONEWWW_FONT_COUNT] = {')
    out += table
    out.append('};')
    OUT.write_text('\n'.join(out) + '\n', newline='\n')
    print(f'{OUT.name}: {len(FACES)} faces, about {total} bytes')


if __name__ == '__main__':
    main()
