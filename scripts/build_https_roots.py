"""Build the bounded public root set from the pinned Mozilla PEM input."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import warnings
from cryptography import x509
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa

ROOT=Path(__file__).resolve().parents[1]
PREFIXES=('ISRG Root ','GTS Root ','Amazon Root CA ','DigiCert ','GlobalSign','USERTrust ','Sectigo Public Server ')
# Keep additions exact rather than trusting all roots from another issuer.
# Go Daddy G2 anchors archive.org without its legacy SHA-1 Class 2 path.
EXACT_COMMON_NAMES=frozenset(('SSL.com TLS ECC Root CA 2022','SSL.com TLS RSA Root CA 2022',
                              'Go Daddy Root Certificate Authority - G2'))

def write_embedded(directory, chosen, source_digest, as_of):
    """Keep generated DER data in the project; firmware never reads build output."""
    directory.mkdir(parents=True,exist_ok=True)
    der=b'';offsets=[0]
    for certificate in chosen:
        der+=certificate.public_bytes(serialization.Encoding.DER);offsets.append(len(der))
    if len(der)>65535:raise RuntimeError('Embedded certificate offsets exceed uint16_t')
    notice=('/* SPDX-License-Identifier: MPL-2.0\n'
            ' * Generated by scripts/build_https_roots.py; do not edit.\n'
            f' * Mozilla public roots selected {as_of}.\n'
            f' * Pinned source SHA256: {source_digest}\n'
            ' * Source and license: third_party/mozilla-ca/.\n'
            ' */\n')
    header=(notice+'#ifndef APPLETINI_HTTP_ROOTS_H\n#define APPLETINI_HTTP_ROOTS_H\n'
            '#include "mbedtls/x509_crt.h"\n'
            f'#define HTTP_BUILTIN_ROOT_COUNT {len(chosen)}U\n'
            f'#define HTTP_BUILTIN_ROOT_DER_BYTES {len(der)}U\n'
            '/* Append public anchors to an initialized chain. DER buffers remain\n'
            ' * borrowed from read-only firmware until the chain is freed. */\n'
            'int http_builtin_roots_load(mbedtls_x509_crt *chain);\n#endif\n')
    source=[notice,'#include "http_roots.h"\n#include <stdint.h>\n',
            'static const unsigned char root_der[HTTP_BUILTIN_ROOT_DER_BYTES] = {\n']
    for at in range(0,len(der),16):source.append('    '+','.join(f'0x{b:02x}' for b in der[at:at+16])+',\n')
    source+=['};\nstatic const uint16_t root_offsets[HTTP_BUILTIN_ROOT_COUNT + 1U] = {\n    ',
             ','.join(str(n) for n in offsets),'\n};\n',
             'int http_builtin_roots_load(mbedtls_x509_crt *chain)\n{\n'
             '    if (!chain) return MBEDTLS_ERR_X509_BAD_INPUT_DATA;\n'
             '    for (unsigned i=0;i<HTTP_BUILTIN_ROOT_COUNT;++i) {\n'
             '        int result=mbedtls_x509_crt_parse_der_nocopy(chain,root_der+root_offsets[i],\n'
             '                         (size_t)(root_offsets[i+1U]-root_offsets[i]));\n'
             '        if (result) return result;\n'
             '    }\n    return 0;\n}\n']
    (directory/'http_roots.h').write_text(header,newline='\n')
    (directory/'http_roots.c').write_text(''.join(source),newline='\n')
    return der

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source',type=Path,default=ROOT/'third_party/mozilla-ca/cacert.pem')
    p.add_argument('--output',type=Path,default=ROOT/'software/https_setup')
    p.add_argument('--embedded-dir',type=Path,
                   help='generated C/header destination; default frontend for the normal bundle, otherwise output directory')
    p.add_argument('--as-of',default='2026-10-29')
    a=p.parse_args();raw=a.source.read_bytes();at=datetime.fromisoformat(a.as_of).replace(tzinfo=timezone.utc)
    with warnings.catch_warnings():
        warnings.simplefilter('ignore');certs=x509.load_pem_x509_certificates(raw)
    chosen=[]
    for c in certs:
        cn=c.subject.get_attributes_for_oid(x509.NameOID.COMMON_NAME)
        if not cn or not (cn[0].value.startswith(PREFIXES) or cn[0].value in EXACT_COMMON_NAMES):continue
        if not c.not_valid_before_utc<=at<c.not_valid_after_utc:continue
        key=c.public_key()
        if isinstance(key,rsa.RSAPublicKey) and key.key_size<=4096:pass
        elif isinstance(key,ec.EllipticCurvePublicKey) and key.curve.name in ('secp256r1','secp384r1'):pass
        else:continue
        chosen.append(c)
    chosen.sort(key=lambda c:c.subject.rfc4514_string())
    digest=hashlib.sha256(raw).hexdigest()
    text=(f'# Appletini bounded public roots, selected {a.as_of}.\n'
          '# Source: https://curl.se/ca/cacert.pem (Mozilla, MPL 2.0).\n'
          f'# Full source SHA256: {digest}\n'
          '# This subset does not trust every public issuer. No test CA is included.\n\n').encode()
    records=[]
    for c in chosen:
        pem=c.public_bytes(serialization.Encoding.PEM);text+=pem+b'\n'
        records.append({'subject':c.subject.rfc4514_string(),'not_after':c.not_valid_after_utc.isoformat(),
                        'der_sha256':hashlib.sha256(c.public_bytes(serialization.Encoding.DER)).hexdigest()})
    if not chosen or len(text)>65567:raise RuntimeError('Public root policy exceeds the firmware file budget')
    embedded=a.embedded_dir
    if embedded is None:
        embedded=ROOT/'ps_sources/frontend' if a.output.resolve()==(ROOT/'software/https_setup').resolve() else a.output
    der=write_embedded(embedded,chosen,digest,a.as_of)
    a.output.mkdir(parents=True,exist_ok=True);(a.output/'ATNETCA.PEM').write_bytes(text)
    (a.output/'roots.json').write_text(json.dumps({'source':'https://curl.se/ca/cacert.pem','source_sha256':digest,
        'as_of':a.as_of,'pem_bytes':len(text),'sha256':hashlib.sha256(text).hexdigest(),
        'embedded_der_bytes':len(der),'embedded_der_sha256':hashlib.sha256(der).hexdigest(),
        'roots':records},indent=2)+'\n',newline='\n')
    print(f'Built {len(chosen)} public roots, {len(text)}/65567 PEM bytes, {len(der)} embedded DER bytes')

if __name__=='__main__':main()
