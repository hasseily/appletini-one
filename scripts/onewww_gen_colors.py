"""Generate the CSS colour names of ONEWWW from Pillow's colour table.

Output: ps_sources/frontend/onewww_css_colors.c, sorted for a binary
search. A colour is 12 bits (0RGB), as a Super Hi-Res palette entry.
"""
from pathlib import Path

from PIL import ImageColor

OUT = (Path(__file__).resolve().parents[1] /
       "ps_sources/frontend/onewww_css_colors.c")


def main():
    names = {}
    for name in ImageColor.colormap:
        r, g, b = ImageColor.getrgb(name)[:3]
        names[name.lower()] = ((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4)
    out = ["/* Generated by scripts/onewww_gen_colors.py. Do not edit. */",
           '#include "onewww_css.h"', "",
           "const onewww_css_color_t onewww_css_colors[] = {"]
    for name in sorted(names):
        out.append(f'    {{"{name}", 0x{names[name]:04X}}},')
    out += ["};", f"const unsigned onewww_css_color_count = {len(names)}U;"]
    OUT.write_text("\n".join(out) + "\n", newline="\n", encoding="ascii")
    print(f"{OUT.name}: {len(names)} colours")


if __name__ == "__main__":
    main()
