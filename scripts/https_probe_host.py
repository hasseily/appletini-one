#!/usr/bin/env python3
"""Controlled HTTPS peer and UART runner for the CPU0 checkpoint.

Private test keys and logs stay under build/. Only the public test CA enters
the opt-in probe firmware. No entropy or private key is written to a log.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timedelta, timezone
import hashlib
import ipaddress
import http.server
import json
import os
from pathlib import Path
import re
import socket
import ssl
import threading
import time

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import NameOID

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build/https-cpu0-checkpoint"
NAME = "checkpoint.appletini.test"
BODY = bytes(i % 251 for i in range(65536))


def prepare():
    OUT.mkdir(parents=True, exist_ok=True)
    now = datetime.now(timezone.utc)
    for label in ("trusted", "untrusted"):
        key_file = OUT / f"{label}-ca-key.pem"
        cert_file = OUT / f"{label}-ca.pem"
        if key_file.exists() and cert_file.exists():
            key = serialization.load_pem_private_key(key_file.read_bytes(), password=None)
            ca = x509.load_pem_x509_certificate(cert_file.read_bytes())
        else:
            key = ec.generate_private_key(ec.SECP256R1())
            subject = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, f"Appletini {label} test CA")])
            ca = (x509.CertificateBuilder().subject_name(subject).issuer_name(subject)
                  .public_key(key.public_key()).serial_number(x509.random_serial_number())
                  .not_valid_before(now - timedelta(days=1)).not_valid_after(now + timedelta(days=365))
                  .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
                  .add_extension(x509.KeyUsage(False, False, False, False, False, True, True, False, False), critical=True)
                  .sign(key, hashes.SHA256()))
            key_file.write_bytes(key.private_bytes(serialization.Encoding.PEM,
                serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
            cert_file.write_bytes(ca.public_bytes(serialization.Encoding.PEM))
        server_key = ec.generate_private_key(ec.SECP256R1())
        subject = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, NAME)])
        leaf = (x509.CertificateBuilder().subject_name(subject).issuer_name(ca.subject)
                .public_key(server_key.public_key()).serial_number(x509.random_serial_number())
                .not_valid_before(now - timedelta(days=1)).not_valid_after(now + timedelta(days=30))
                .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
                .add_extension(x509.SubjectAlternativeName([x509.DNSName(NAME),
                    x509.IPAddress(ipaddress.ip_address("10.17.1.17"))]), critical=False)
                .add_extension(x509.ExtendedKeyUsage([x509.oid.ExtendedKeyUsageOID.SERVER_AUTH]), critical=False)
                .add_extension(x509.KeyUsage(True, False, False, False, False, False, False, False, False), critical=True)
                .sign(key, hashes.SHA256()))
        (OUT / f"{label}-server-key.pem").write_bytes(server_key.private_bytes(
            serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
        (OUT / f"{label}-server.pem").write_bytes(leaf.public_bytes(serialization.Encoding.PEM))
        if label == "trusted":
            der = ca.public_bytes(serialization.Encoding.DER)
            header = ("/* Public test CA only. Generated by scripts/https_probe_host.py prepare. */\n"
                      "#ifndef HTTPS_PROBE_TEST_CA_H\n#define HTTPS_PROBE_TEST_CA_H\n"
                      "static const unsigned char https_probe_ca_der[] = {\n")
            for at in range(0, len(der), 12):
                header += "    " + ", ".join(f"0x{b:02x}" for b in der[at:at + 12]) + ",\n"
            header += "};\n#endif\n"
            (ROOT / "ps_sources/frontend/https_probe_test_ca.h").write_text(header, encoding="utf-8")
    print("Prepared ECDSA test certificates and public firmware trust anchor.")
    print("Expected response SHA256:", hashlib.sha256(BODY).hexdigest())


class Handler(http.server.BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def do_GET(self):
        if self.path != "/probe":
            self.send_error(404)
            return
        self.send_response(200)
        self.send_header("Content-Length", str(len(BODY)))
        self.send_header("Content-Type", "application/octet-stream")
        self.send_header("Connection", "close")
        self.end_headers()
        try:
            for at in range(0, len(BODY), 256):
                self.wfile.write(BODY[at:at + 256])
                self.wfile.flush()
                time.sleep(0.02)
        except (ConnectionError, ssl.SSLError):
            pass

    def log_message(self, fmt, *args):
        print("[https-server]", self.client_address[0], fmt % args, flush=True)


class TLSServer(http.server.ThreadingHTTPServer):
    def process_request_thread(self, request, address):
        request.settimeout(30)
        try:
            peer = self.tls_context.wrap_socket(request, server_side=True)
        except (ssl.SSLError, OSError):
            request.close()
            return
        super().process_request_thread(peer, address)


def serve(bind):
    servers = []
    for label, port in (("trusted", 8443), ("untrusted", 8444)):
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.minimum_version = context.maximum_version = ssl.TLSVersion.TLSv1_2
        context.set_ciphers("ECDHE-ECDSA-AES128-GCM-SHA256")
        context.set_ecdh_curve("prime256v1")
        context.load_cert_chain(OUT / f"{label}-server.pem", OUT / f"{label}-server-key.pem")
        server = TLSServer((bind, port), Handler)
        server.tls_context = context
        threading.Thread(target=server.serve_forever, daemon=True).start()
        servers.append(server)
        print(f"Serving {label} TLS 1.2 peer on {bind}:{port}", flush=True)
    try:
        while True:
            time.sleep(1)
    except KeyboardInterrupt:
        for server in servers:
            server.shutdown()


def serial_command(ser, command, marker=None, timeout=3):
    wire = (":" + command + "\r\n").encode("ascii")
    # CPU0 polls this console between compositor passes. A full line sent at
    # 921600 baud can overflow its hardware RX FIFO before the next poll.
    for at in range(0, len(wire), 8):
        ser.write(wire[at:at + 8])
        ser.flush()
        time.sleep(0.01)
    result = bytearray()
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        result.extend(ser.read(max(1, ser.in_waiting)))
        if marker and marker.encode() in result:
            break
    text = result.decode("utf-8", errors="replace")
    return re.sub(r"(?i)((?:https seed|http provision) )[0-9a-f]+", r"\1[redacted]", text)


def run(args):
    import serial
    OUT.mkdir(parents=True, exist_ok=True)
    with serial.Serial(args.serial_port, args.baud, timeout=0.05) as ser:
        ser.reset_input_buffer()
        if args.command:
            text = serial_command(ser, " ".join(args.command), timeout=args.timeout)
            print(text)
            (OUT / "last-command.txt").write_text(text, encoding="utf-8")
            return
        seed = os.urandom(48)
        text = serial_command(ser, "https seed " + seed.hex(), "fresh seed accepted", 3)
        if "fresh seed accepted" not in text:
            raise RuntimeError("Firmware did not accept fresh entropy: " + text)
        name = "wrong.appletini.test" if args.case == "hostname" else NAME
        port = 8444 if args.case == "untrusted" else 8443
        epoch = int(time.time()) + (400 * 86400 if args.case == "expired" else 0)
        run_start = time.monotonic()
        text += serial_command(ser, f"https run {args.peer} {port} {name} {epoch}",
                               "[https] done", args.timeout)
        wall_seconds = time.monotonic() - run_start
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    stem = OUT / f"{stamp}-{args.case}"
    stem.with_suffix(".txt").write_text(text, encoding="utf-8")
    report = {"case": args.case, "label": args.label, "peer": args.peer, "time_utc": stamp,
              "wall_seconds": wall_seconds,
              "expected_sha256": hashlib.sha256(BODY).hexdigest(), "phases": []}
    for line in text.splitlines():
        if line.startswith(("[https-phase]", "[https-result]")):
            fields = dict(re.findall(r"(\w+)=([^ ]+)", line))
            for key, value in list(fields.items()):
                if value.isdigit() or value.startswith(("-", "0x")):
                    try:
                        fields[key] = int(value, 16 if value.startswith("0x") else 10)
                    except ValueError:
                        pass
            if line.startswith("[https-phase]"):
                report["phases"].append(fields)
            else:
                report["result"] = fields
        elif line.startswith("[https-sha256]"):
            report["sha256"] = line.split()[-1]
    result = report.get("result", {})
    target_seconds = sum(p.get("us", 0) for p in report["phases"]) / 1e6
    report["target_seconds"] = target_seconds
    report["timing_valid"] = 0.85 < target_seconds / wall_seconds < 1.15
    report["workload"] = {
        "capture_active": len(report["phases"]) == 3 and all(
            p.get("health") == 1 and p.get("capture_records", 0) > 0 and
            p.get("video_frames", 0) > 0 for p in report["phases"]),
        "usb_reports": sum(p.get("hid", 0) + p.get("xbox", 0) for p in report["phases"]),
        "sd_cache_misses": sum(p.get("cache_misses", 0) for p in report["phases"]),
    }
    if args.case == "valid":
        report["pass"] = (result.get("rc") == 0 and result.get("verify") == 0 and
                          result.get("status") == 200 and result.get("body") == len(BODY) and
                          result.get("body_valid") == 1 and report.get("sha256") == report["expected_sha256"])
    else:
        expected_flag = {"hostname": 4, "untrusted": 8, "expired": 1}[args.case]
        flags = result.get("verify", 0)
        report["pass"] = (result.get("rc", 0) != 0 and flags != 0xFFFFFFFF and
                          flags & expected_flag != 0 and result.get("body") == 0)
    if args.require_workload:
        phases = report["phases"]
        active = next((p for p in phases if p.get("name") == "https"), {})
        errors = ("gaps", "oversized", "resync", "hid_errors", "xbox_errors",
                  "sd_errors", "sd_crc_errors")
        report["workload_pass"] = (
            [p.get("name") for p in phases] == ["baseline", "https", "recovery"] and
            all(p.get("health") == 1 and p.get("capture_records", 0) > 0 and
                p.get("video_frames", 0) > 0 and p.get("blits", 0) > 0 and
                p.get("cache_misses", 0) > 0 and all(p.get(key) == 0 for key in errors)
                for p in phases) and
            active.get("hid", 0) > 0 and active.get("xbox", 0) > 0)
        report["pass"] = report["pass"] and report["workload_pass"]
    stem.with_suffix(".json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(text)
    print("Report:", stem.with_suffix(".json"))
    if not report["pass"]:
        raise SystemExit("HTTPS checkpoint case failed")
    if not report["timing_valid"]:
        raise SystemExit("Target timer disagrees with host elapsed time")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("prepare", "serve", "run", "ip"))
    parser.add_argument("--bind", default="0.0.0.0")
    parser.add_argument("--peer")
    parser.add_argument("--serial-port", default="COM13")
    parser.add_argument("--baud", type=int, default=921600)
    parser.add_argument("--case", choices=("valid", "hostname", "untrusted", "expired"), default="valid")
    parser.add_argument("--timeout", type=float, default=50)
    parser.add_argument("--label", default="")
    parser.add_argument("--require-workload", action="store_true",
                        help="also require active capture, HID/Xbox, SD misses, and zero service errors")
    parser.add_argument("--command", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    if args.mode == "prepare":
        prepare()
    elif args.mode == "serve":
        serve(args.bind)
    elif args.mode == "ip":
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            sock.connect(("1.1.1.1", 80))
            print(sock.getsockname()[0])
    else:
        if not args.command and not args.peer:
            parser.error("run needs --peer or --command")
        run(args)


if __name__ == "__main__":
    main()
