"""Generate the HTML entity table of ONEWWW from Python's html.entities.

Output: ps_sources/frontend/onewww_entities.c. Names are sorted for a
binary search. An entity with two code points keeps the first one.
"""
from html.entities import html5
from pathlib import Path

OUT = (Path(__file__).resolve().parents[1] /
       "ps_sources/frontend/onewww_entities.c")


def main():
    names = {}
    for key, value in html5.items():
        name = key.rstrip(";")
        code = ord(value[0])
        if code > 0xFFFF:
            code = ord("?")
        legacy = 0 if key.endswith(";") else 1
        old = names.get(name, (code, 0))
        names[name] = (code, old[1] | legacy)
    out = ["/* Generated by scripts/onewww_gen_entities.py. Do not edit. */",
           '#include "onewww_dom.h"', "",
           "const onewww_entity_t onewww_entities[] = {"]
    for name in sorted(names):
        code, legacy = names[name]
        out.append(f'    {{"{name}", {code}, {legacy}}},')
    out += ["};", f"const unsigned onewww_entity_count = {len(names)}U;"]
    OUT.write_text("\n".join(out) + "\n", newline="\n", encoding="ascii")
    print(f"{OUT.name}: {len(names)} entities")


if __name__ == "__main__":
    main()
