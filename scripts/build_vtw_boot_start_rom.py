#!/usr/bin/env python3
"""Build a firmware-only C8 startup gate without changing the retained C7 ROM."""

import argparse
import hashlib
import importlib.util
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "ps_sources/frontend/boot_menu_vtw_start_rom.h"
BUILD = ROOT / "build/vtw_boot_start_rom"

OLD = """          sta ALTZP_OFF
          sta BM_IO,y
          txa
          bne mid_send
"""
NEW = """          sta ALTZP_OFF
          sta BM_IO,y
          txa
          ; This path belongs only to a physical IIe/enhanced IIe. Report
          ; its identity before CPU0 applies the aux policy and the optional
          ; vTW startup hold. II/II+ and IIgs keep the original return path.
          sta BM_IO,y
vtw_boot_gate_control:
          lda #$00
          bne vtw_boot_gate_control
native_slot3_control:
          lda #$00
          beq native_slot3_done
          ; The stock cold-start probe ran before Appletini supplied aux
          ; RAM. Show the internal 80-column ROM before ProDOS scans slots.
          sta $C00A
native_slot3_done:
          rts
"""


def build():
    spec = importlib.util.spec_from_file_location(
        "boot_menu_builder", ROOT / "scripts/build_boot_menu_rom.py")
    builder = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(builder)
    slot, reloc, _c8, symbols = builder.build()
    source = builder.SRC_PATH.read_text(encoding="utf-8")
    if source.count(OLD) != 1:
        raise ValueError("retained IIe report tail changed; audit the gate again")
    BUILD.mkdir(parents=True, exist_ok=True)
    patched = BUILD / "boot_menu_vtw_start.a65"
    patched.write_text(source.replace(OLD, NEW), encoding="utf-8")
    builder.SRC_PATH = patched
    new_slot, new_reloc, c8, new_symbols = builder.build()
    if new_slot != slot or new_reloc != reloc:
        raise ValueError("startup gate changed the retained C7 slot ROM")
    for name in ("VBL_MOUSECARD_SYNC", "WAIT_VBL_START", "MACHINE_ID_REPORT"):
        if symbols[name] != new_symbols[name]:
            raise ValueError(f"retained C7 call address changed: {name}")
    for path, data in ((builder.MEM_PATH, slot), (builder.RELOC_PATH, reloc)):
        retained = bytes(int(line, 16) for line in path.read_text().split())
        if retained != data:
            raise ValueError(f"retained C7 source bytes differ: {path}")
    return slot, reloc, c8, new_symbols


def header_text():
    slot, reloc, c8, symbols = build()
    gate = symbols["VTW_BOOT_GATE_CONTROL"] + 1 - 0xC800
    native_c3 = symbols["NATIVE_SLOT3_CONTROL"] + 1 - 0xC800
    delay_x = symbols["DELAY_FRAME_X_OPCODE"] + 1 - 0xC800
    delay_y = symbols["DELAY_FRAME_Y_OPCODE"] + 1 - 0xC800
    lines = [
        "#ifndef BOOT_MENU_VTW_START_ROM_H",
        "#define BOOT_MENU_VTW_START_ROM_H",
        "",
        "#include <stdint.h>",
        "",
        "/* Generated by scripts/build_vtw_boot_start_rom.py from",
        " * software/boot_menu_slot7.a65. Install only while the initial",
        " * Apple RESET is held; C7 code and its C8 call addresses stay unchanged.",
        f" * Retained C7 SHA-256: {hashlib.sha256(slot).hexdigest()}",
        f" * Retained relocation SHA-256: {hashlib.sha256(reloc).hexdigest()}",
        " * The hold and native slot-3 selection follow only a physical IIe report. */",
        f"#define BOOT_MENU_VTW_C8_GATE_OFFSET    0x{gate:02X}U",
        f"#define BOOT_MENU_NATIVE_C3_OFFSET      0x{native_c3:02X}U",
        f"#define BOOT_MENU_VTW_C8_DELAY_X_OFFSET 0x{delay_x:02X}U",
        f"#define BOOT_MENU_VTW_C8_DELAY_Y_OFFSET 0x{delay_y:02X}U",
        "",
        "static const uint8_t boot_menu_vtw_start_c8_rom[256] = {",
    ]
    for i in range(0, len(c8), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}U" for b in c8[i:i + 16]) + ",")
    lines.extend(["};", "", "#endif /* BOOT_MENU_VTW_START_ROM_H */", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = header_text().encode("ascii")
    if args.check:
        if HEADER.read_bytes() != expected:
            raise SystemExit("firmware-only vTW C8 ROM header is stale")
        print("PASS firmware-only C8 gate; retained C7 bytes and call addresses match")
    else:
        HEADER.write_bytes(expected)
        print(f"Wrote {HEADER}")


if __name__ == "__main__":
    main()
